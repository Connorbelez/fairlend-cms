import { execFile } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

const exec = promisify(execFile);
const root = path.resolve(import.meta.dirname, "..");
const manifest = JSON.parse(
  await fs.readFile(path.join(root, "creative", "tts-manifest.json"), "utf8"),
);
const outputDirectory = path.join(root, "audio", "voice");
await fs.mkdir(outputDirectory, { recursive: true });

for (const item of manifest) {
  const aiff = path.join(outputDirectory, `${item.id}.aiff`);
  const wav = path.join(outputDirectory, `${item.id}.wav`);
  const baseRate = item.id === "06-stakeholder-campaign" ? 225 : 185;
  const rate = String(Math.round(baseRate * item.speed));
  await exec("say", ["-v", "Samantha", "-r", rate, "-o", aiff, item.input]);
  await exec("ffmpeg", [
    "-y",
    "-loglevel",
    "error",
    "-i",
    aiff,
    "-ar",
    "48000",
    "-ac",
    "1",
    wav,
  ]);
  await fs.unlink(aiff);
  process.stdout.write(`generated scratch ${path.relative(root, wav)}\n`);
}

await fs.writeFile(
  path.join(outputDirectory, ".scratch-voice"),
  "These files are timing proxies generated by macOS say. Replace them with generate-openai-tts.mjs before final delivery.\n",
);
